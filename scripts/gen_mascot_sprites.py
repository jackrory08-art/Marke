"""Generates dashboard/static/js/mascot-sprites.js: the 'Surveyor' field robot, 24x24."""
import json
import os
W = H = 24

def blank(): return [['.'] * W for _ in range(H)]
def put(g, x, y, c):
    if 0 <= x < W and 0 <= y < H: g[y][x] = c
def rect(g, x, y, w, h, c):
    for yy in range(y, y + h):
        for xx in range(x, x + w): put(g, xx, yy, c)
def box(g, x, y, w, h, line, fill):
    rect(g, x, y, w, h, line); rect(g, x + 1, y + 1, w - 2, h - 2, fill)

LENS_OUTER = {6: (10, 13), 7: (9, 14), 8: (8, 15), 9: (8, 15), 10: (8, 15), 11: (9, 14), 12: (10, 13)}
LENS_INNER = {7: (10, 13), 8: (9, 14), 9: (9, 14), 10: (9, 14), 11: (10, 13)}

def base(tip='d'):
    g = blank()
    rect(g, 11, 2, 2, 2, 'k')               # antenna stalk
    rect(g, 11, 0, 2, 2, tip)               # antenna tip
    box(g, 4, 4, 16, 10, 'k', 'b')          # head
    for y in (7, 9, 11):                    # vents
        put(g, 6, y, 'd'); put(g, 17, y, 'd')
    for y, (a, b) in LENS_OUTER.items(): rect(g, a, y, b - a + 1, 1, 'k')
    for y, (a, b) in LENS_INNER.items(): rect(g, a, y, b - a + 1, 1, 'l')
    rect(g, 9, 14, 6, 1, 'd'); put(g, 9, 14, 'k'); put(g, 14, 14, 'k')   # neck
    box(g, 6, 15, 12, 5, 'k', 'b')          # body
    rect(g, 9, 17, 6, 1, 'd')               # chest panel
    rect(g, 4, 16, 2, 3, 'k'); rect(g, 18, 16, 2, 3, 'k')   # arms
    box(g, 3, 20, 7, 3, 'k', 'd'); box(g, 14, 20, 7, 3, 'k', 'd')   # treads
    return g

def pupil(g, px, py):
    rect(g, px, py, 2, 2, 'a')

def blink(g):
    for y, (a, b) in LENS_INNER.items(): rect(g, a, y, b - a + 1, 1, 'b')
    rect(g, 9, 9, 6, 1, 'k')

def rows(g): return [''.join(r) for r in g]

S = {}
# idle: look, blink
g = base(); pupil(g, 11, 8); S['idle'] = [rows(g)]
g = base(); blink(g); S['idle'].append(rows(g))
# scanning: eye sweeps left-right, antenna blinks
S['scanning'] = []
for i, px in enumerate((9, 11, 13, 11)):
    g = base('a' if i % 2 == 0 else 'd'); pupil(g, px, 8); S['scanning'].append(rows(g))
# verifying: looks at a sheet; a line lights up each frame
S['verifying'] = []
for i in range(3):
    g = base(); pupil(g, 13, 8)
    box(g, 18, 11, 6, 10, 'k', 'l')
    for j, y in enumerate((13, 15, 17)): rect(g, 19, y, 4, 1, 'a' if j == i else 'd')
    S['verifying'].append(rows(g))
# analysing: looks up, thought dots fill in
S['analysing'] = []
for i in range(3):
    g = base(); pupil(g, 11, 7)
    for j, x in enumerate((15, 18, 21)): rect(g, x, 1, 2, 2, 'a' if j <= i else 'd')
    S['analysing'].append(rows(g))
# found: antenna flash
g = base('a'); rect(g, 10, 0, 4, 3, 'a'); pupil(g, 11, 8); S['found'] = [rows(g)]
g = base('a'); pupil(g, 11, 8)
for x, y in ((8, 2), (15, 2), (7, 0), (16, 0)): put(g, x, y, 'a')
S['found'].append(rows(g))
# error: grey, X eyes (the renderer greys the accent)
g = base('d')
for x, y in ((11, 8), (13, 8), (12, 9), (11, 10), (13, 10)): put(g, x, y, 'x')
S['error'] = [rows(g)]
# offline: closed lens, dimmed by the renderer
g = base('d'); blink(g); S['offline'] = [rows(g)]

for name, frames in S.items():
    for f in frames:
        assert len(f) == H and all(len(r) == W for r in f), name

js = ['// Generated by scripts/gen_mascot_sprites.py: "Surveyor", an original 24x24 field robot.',
      '// Palette-indexed rows: . transparent, k ink outline, b body, d shade, l lens glass,',
      '// a accent, x mark. mascot.js maps the letters to theme colours.',
      '', 'export const SIZE = 24;', '',
      'export const FRAME_MS = { idle: 700, scanning: 220, verifying: 450, analysing: 500, found: 300 };', '',
      'export const SPRITES = {']
for name, frames in S.items():
    js.append(f'  {name}: [')
    for f in frames:
        js.append('    [')
        js += [f'      {json.dumps(r)},' for r in f]
        js.append('    ],')
    js.append('  ],')
js.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dashboard', 'static', 'js', 'mascot-sprites.js'), 'w').write('\n'.join(js) + '\n')
# ascii preview of a few frames
for name in ('idle', 'verifying'):
    print(name); print('\n'.join(S[name][0 if name=='idle' else 1]))
